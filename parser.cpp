#include "parser.h"
#include <stdexcept>

using namespace std;

// Recursive Descent Parser for propositional logic formulas.
class Parser {
    vector<Token> tokens;
    size_t pos = 0;

    // Checks whether the current token matches the given type.
    // If it matches, advances to the next token.
    bool match(TokenType type) {
        if (pos < tokens.size() && tokens[pos].type == type) {
            pos++;
            return true;
        }
        return false;
    }

    // Parses biconditional expressions (<->).
    // Biconditional has the lowest precedence.
    shared_ptr<ASTNode> parseIff() {
        auto node = parseImplies();

        while (match(IFF)) {
            auto right = parseImplies();
            node = make_shared<ASTNode>(IFF_NODE, "<->", node, right);
        }

        return node;
    }

    // Parses implication expressions (->).
    // Implication is right-associative.
    shared_ptr<ASTNode> parseImplies() {
        auto left = parseOr();

        if (match(IMPLIES)) {
            auto right = parseImplies();
            return make_shared<ASTNode>(IMPLIES_NODE, "->", left, right);
        }

        return left;
    }

    // Parses OR expressions (|).
    shared_ptr<ASTNode> parseOr() {
        auto node = parseAnd();

        while (match(OR)) {
            auto right = parseAnd();
            node = make_shared<ASTNode>(OR_NODE, "|", node, right);
        }

        return node;
    }

    // Parses AND expressions (&).
    shared_ptr<ASTNode> parseAnd() {
        auto node = parseUnary();

        while (match(AND)) {
            auto right = parseUnary();
            node = make_shared<ASTNode>(AND_NODE, "&", node, right);
        }

        return node;
    }

    // Parses NOT expressions (~), variables, and parenthesized formulas.
    // NOT has the highest operator precedence.
    shared_ptr<ASTNode> parseUnary() {
        // If NOT is found, parse its operand recursively.
        if (match(NOT)) {
            auto child = parseUnary();
            return make_shared<ASTNode>(NOT_NODE, "~", child);
        }

        // Parse an expression inside parentheses.
        if (match(LPAREN)) {
            auto node = parseIff();

            // Ensure that the closing parenthesis exists.
            if (!match(RPAREN))
                throw runtime_error("Missing closing parenthesis");

            return node;
        }

        // Create a leaf node for a variable.
        if (pos < tokens.size() && tokens[pos].type == VARIABLE) {
            string value = tokens[pos++].value;
            return make_shared<ASTNode>(VAR_NODE, value);
        }

        // Report an error if the token is invalid or missing.
        throw runtime_error("Unexpected token in formula");
    }

public:
    // Stores the tokens generated by the lexer.
    Parser(vector<Token> t) : tokens(t) {}

    // Parses the complete formula and returns the AST root.
    shared_ptr<ASTNode> run() {
        if (tokens.empty())
            throw runtime_error("Formula cannot be empty");

        auto root = parseIff();

        // Ensure that all tokens have been consumed.
        if (pos != tokens.size())
            throw runtime_error("Unexpected token at end of formula");

        return root;
    }
};

// Converts the input formula into tokens and then parses them into an AST.
shared_ptr<ASTNode> parse(const string &formula) {
    vector<Token> tokens = tokenize(formula);
    Parser parser(tokens);
    return parser.run();
}